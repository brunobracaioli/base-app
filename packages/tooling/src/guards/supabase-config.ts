import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import * as TOML from 'smol-toml';

type ConfigObject = Record<string, unknown>;
type PathSegments = readonly string[];

export class SupabaseConfigError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'SupabaseConfigError';
  }
}

export interface ConfigFragment {
  readonly name: string;
  readonly contents: string;
}

export interface RenderedSupabaseConfig {
  readonly text: string;
  readonly coreOverrides: readonly string[];
  readonly approvedOverrides: readonly string[];
}

const protectedFixedPaths = new Set([
  'api.enabled',
  'auth.jwt_expiry',
  'auth.enable_anonymous_sign_ins',
  'auth.enable_manual_linking',
  'auth.additional_redirect_urls',
  'auth.email.secure_password_change',
  'auth.email.double_confirm_changes',
  'auth.email.enable_confirmations',
  'auth.email.otp_length',
  'auth.email.otp_expiry',
  'auth.rate_limit.sign_in_sign_ups',
  'auth.rate_limit.token_verifications',
  'auth.rate_limit.email_sent',
  'auth.email.smtp.enabled',
  'auth.email.smtp.pass',
  'auth.hook.before_user_created.enabled',
  'auth.hook.before_user_created.uri',
]);

const generatedHeader = [
  '# Generated by pnpm supabase:config. Do not edit this file.',
  '# Sources: config.base.toml and config.d/*.toml, merged in filename order.',
];

function isPlainObject(value: unknown): value is ConfigObject {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return false;
  const prototype = Object.getPrototypeOf(value) as unknown;
  return prototype === Object.prototype || prototype === null;
}

function cloneTomlValue(value: unknown): unknown {
  if (Array.isArray(value)) return value.map((item) => cloneTomlValue(item));
  if (!isPlainObject(value)) return value;

  const cloned: ConfigObject = Object.create(null) as ConfigObject;
  for (const [key, child] of Object.entries(value)) cloned[key] = cloneTomlValue(child);
  return cloned;
}

function parseToml(contents: string, source: string): ConfigObject {
  try {
    const parsed: unknown = TOML.parse(contents, { unsafeKeyBehaviour: 'throw' });
    if (!isPlainObject(parsed))
      throw new SupabaseConfigError(`${source} must contain a TOML table.`);
    return cloneTomlValue(parsed) as ConfigObject;
  } catch (error) {
    if (error instanceof SupabaseConfigError) throw error;
    // Parser diagnostics can contain source excerpts; keep secrets out of CLI output.
    throw new SupabaseConfigError(`Invalid TOML in ${source}.`);
  }
}

function mergeObjects(base: ConfigObject, overlay: ConfigObject): ConfigObject {
  const merged = cloneTomlValue(base) as ConfigObject;
  for (const [key, overlayValue] of Object.entries(overlay)) {
    const baseValue = merged[key];
    if (isPlainObject(baseValue) && isPlainObject(overlayValue)) {
      merged[key] = mergeObjects(baseValue, overlayValue);
    } else {
      merged[key] = cloneTomlValue(overlayValue);
    }
  }
  return merged;
}

function getAtPath(root: unknown, segments: PathSegments): unknown {
  let value = root;
  for (const segment of segments) {
    if (!isPlainObject(value) || !Object.hasOwn(value, segment)) return undefined;
    value = value[segment];
  }
  return value;
}

function tomlValuesEqual(left: unknown, right: unknown): boolean {
  if (Object.is(left, right)) return true;
  if (left instanceof Date && right instanceof Date) return left.getTime() === right.getTime();
  if (Array.isArray(left) && Array.isArray(right)) {
    return (
      left.length === right.length &&
      left.every((value, index) => tomlValuesEqual(value, right[index]))
    );
  }
  if (!isPlainObject(left) || !isPlainObject(right)) return false;
  const leftEntries = Object.entries(left);
  const rightEntries = Object.entries(right);
  if (leftEntries.length !== rightEntries.length) return false;
  return leftEntries.every(
    ([key, value]) => Object.hasOwn(right, key) && tomlValuesEqual(value, right[key]),
  );
}

function changedLeafPaths(before: unknown, after: unknown, prefix: string[] = []): string[][] {
  if (isPlainObject(before) && isPlainObject(after)) {
    const keys = new Set([...Object.keys(before), ...Object.keys(after)]);
    const changes: string[][] = [];
    for (const key of keys) {
      if (!Object.hasOwn(before, key) || !Object.hasOwn(after, key)) {
        const existing = Object.hasOwn(after, key) ? after[key] : before[key];
        changes.push(...leafPaths(existing, [...prefix, key]));
      } else {
        changes.push(...changedLeafPaths(before[key], after[key], [...prefix, key]));
      }
    }
    return changes;
  }
  return tomlValuesEqual(before, after) ? [] : [prefix];
}

function leafPaths(value: unknown, prefix: string[]): string[][] {
  if (!isPlainObject(value) || Object.keys(value).length === 0) return [prefix];
  return Object.entries(value).flatMap(([key, child]) => leafPaths(child, [...prefix, key]));
}

function isProtectedPath(segments: PathSegments): boolean {
  const pathName = segments.join('.');
  if (protectedFixedPaths.has(pathName)) return true;
  if (segments[0] !== 'auth') return false;
  if (segments[1] === 'external' && segments.at(-1) === 'enabled') return true;
  if (segments[1] === 'mfa' && segments.at(-1) === 'enroll_enabled') return true;
  if (segments[1] === 'saml' && segments.at(-1) === 'enabled') return true;
  if (segments[1] === 'oauth_server' && segments.at(-1) === 'enabled') return true;
  if (segments[1] === 'web3' && segments.at(-1) === 'enabled') return true;
  if (
    segments[1] === 'hook' &&
    segments[2] === 'before_user_created' &&
    ['enabled', 'uri'].includes(segments.at(-1) ?? '')
  )
    return true;
  if (
    segments[1] === 'sms' &&
    ['enabled', 'enable_signup', 'enable_confirmations'].includes(segments.at(-1) ?? '')
  )
    return true;
  return false;
}

interface OverrideMarker {
  readonly path: string;
  readonly reason: string;
}

function parseSimpleTomlKeyPath(keyText: string): string[] | null {
  const parts = keyText.split('.').map((part) => part.trim());
  if (parts.length === 0 || parts.some((part) => !/^[A-Za-z0-9_-]+$/.test(part))) return null;
  return parts;
}

function parseOverrideMarkers(fragment: ConfigFragment): OverrideMarker[] {
  const lines = fragment.contents.split(/\r\n|\n|\r/);
  const markers: OverrideMarker[] = [];
  let currentTable: string[] = [];
  let inArrayTable = false;

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index] ?? '';
    if (/^\s*\[\[/.test(line)) {
      inArrayTable = true;
      currentTable = [];
      continue;
    }
    const tableMatch = line.match(/^\s*\[([^\]]+)\]\s*(?:#.*)?$/);
    if (tableMatch) {
      inArrayTable = false;
      const parsedTable = parseSimpleTomlKeyPath(tableMatch[1] ?? '');
      if (parsedTable === null)
        throw new SupabaseConfigError(
          `${fragment.name}:${index + 1}: unsupported table name near allow-override markers.`,
        );
      currentTable = parsedTable;
      continue;
    }

    const markerMatch = line.match(/^\s*#\s*allow-override:\s*([A-Za-z0-9_.-]+)\s+(.+?)\s*$/);
    if (!markerMatch) continue;
    if (inArrayTable)
      throw new SupabaseConfigError(
        `${fragment.name}:${index + 1}: allow-override is not supported inside an array-of-tables.`,
      );

    const markerPath = markerMatch[1] ?? '';
    const reason = markerMatch[2]?.trim() ?? '';
    if (reason.length === 0 || reason.length > 200) {
      throw new SupabaseConfigError(
        `${fragment.name}:${index + 1}: allow-override needs a reason of 1 to 200 characters.`,
      );
    }

    const assignmentLine = lines[index + 1] ?? '';
    const assignmentMatch = assignmentLine.match(/^\s*([A-Za-z0-9_.-]+)\s*=/);
    const assignmentKey = assignmentMatch?.[1];
    const assignmentSegments =
      assignmentKey === undefined ? null : parseSimpleTomlKeyPath(assignmentKey);
    if (assignmentSegments === null) {
      throw new SupabaseConfigError(
        `${fragment.name}:${index + 1}: allow-override must be immediately followed by a simple key assignment.`,
      );
    }
    const fullPath = [...currentTable, ...assignmentSegments].join('.');
    if (fullPath !== markerPath) {
      throw new SupabaseConfigError(
        `${fragment.name}:${index + 1}: allow-override path ${markerPath} does not match the following key ${fullPath}.`,
      );
    }
    if (!isProtectedPath(fullPath.split('.'))) {
      throw new SupabaseConfigError(
        `${fragment.name}:${index + 1}: allow-override may only annotate a protected config key.`,
      );
    }
    if (markers.some((marker) => marker.path === markerPath)) {
      throw new SupabaseConfigError(
        `${fragment.name}:${index + 1}: duplicate allow-override for ${markerPath}.`,
      );
    }
    markers.push({ path: markerPath, reason });
    index += 1;
  }

  return markers;
}

function validateOverrideMarkers(
  before: ConfigObject,
  after: ConfigObject,
  fragment: ConfigFragment,
  markers: readonly OverrideMarker[],
): void {
  const changedProtected = changedLeafPaths(before, after)
    .filter((segments) => segments.length > 0 && isProtectedPath(segments))
    .map((segments) => segments.join('.'));
  const markerPaths = new Set(markers.map((marker) => marker.path));

  for (const pathName of changedProtected) {
    if (!markerPaths.has(pathName)) {
      throw new SupabaseConfigError(
        `${fragment.name}: changing protected key ${pathName} requires a preceding # allow-override marker.`,
      );
    }
  }
  for (const marker of markers) {
    if (!changedProtected.includes(marker.path)) {
      throw new SupabaseConfigError(
        `${fragment.name}: allow-override for ${marker.path} does not correspond to a changed protected key.`,
      );
    }
  }
}

function assertEnvReference(value: unknown, pathName: string): void {
  if (typeof value !== 'string' || !/^env\([A-Z][A-Z0-9_]*\)$/.test(value)) {
    throw new SupabaseConfigError(
      `${pathName} must use an env(NAME) reference; literal secrets are forbidden.`,
    );
  }
}

function checkSecretValues(value: unknown, pathSegments: string[] = []): void {
  if (Array.isArray(value)) {
    value.forEach((child, index) => checkSecretValues(child, [...pathSegments, String(index)]));
    return;
  }
  if (!isPlainObject(value)) {
    const key = pathSegments.at(-1) ?? '';
    const sensitiveLeaf =
      /^(?:secret|secret[_-]?key|password|passwd|pass|smtp[_-]?pass|smtp[_-]?password|token|auth[_-]?token|access[_-]?token|refresh[_-]?token|client[_-]?secret|private[_-]?key|api[_-]?key)$/i;
    if (typeof value === 'string' && value.length > 0 && sensitiveLeaf.test(key)) {
      assertEnvReference(value, pathSegments.join('.'));
    }
    return;
  }
  for (const [key, child] of Object.entries(value))
    checkSecretValues(child, [...pathSegments, key]);
}

function requiredObject(value: unknown, pathName: string): ConfigObject {
  if (!isPlainObject(value)) throw new SupabaseConfigError(`${pathName} must be a TOML table.`);
  return value;
}

function requiredNumber(value: unknown, pathName: string): number {
  if (typeof value !== 'number' || !Number.isInteger(value))
    throw new SupabaseConfigError(`${pathName} must be an integer.`);
  return value;
}

function validateHttpsRedirects(value: unknown): void {
  if (!Array.isArray(value))
    throw new SupabaseConfigError('auth.additional_redirect_urls must be an array.');
  for (const item of value) {
    if (typeof item !== 'string')
      throw new SupabaseConfigError('auth.additional_redirect_urls entries must be strings.');
    let parsed: URL;
    try {
      parsed = new URL(item);
    } catch {
      throw new SupabaseConfigError(
        'auth.additional_redirect_urls may contain only explicit https URLs without wildcards.',
      );
    }
    if (parsed.protocol !== 'https:' || item.includes('*') || parsed.hostname.length === 0) {
      throw new SupabaseConfigError(
        'auth.additional_redirect_urls may contain only explicit https URLs without wildcards.',
      );
    }
  }
}

function validateDisabledSurface(
  value: unknown,
  pathSegments: string[],
  allowOverrides: ReadonlySet<string>,
): void {
  if (Array.isArray(value)) {
    value.forEach((child, index) =>
      validateDisabledSurface(child, [...pathSegments, String(index)], allowOverrides),
    );
    return;
  }
  if (!isPlainObject(value)) return;

  for (const [key, child] of Object.entries(value)) {
    const childPath = [...pathSegments, key];
    const pathName = childPath.join('.');
    if (
      isProtectedPath(childPath) &&
      typeof child === 'boolean' &&
      child &&
      !allowOverrides.has(pathName)
    ) {
      throw new SupabaseConfigError(
        `${pathName} must be false unless it has an approved allow-override marker.`,
      );
    }
    validateDisabledSurface(child, childPath, allowOverrides);
  }
}

export function validateSupabaseConfig(
  config: unknown,
  approvedOverrides: readonly string[] = [],
): void {
  const root = requiredObject(config, 'config.toml');
  const api = requiredObject(root.api, 'api');
  if (api.enabled !== false) throw new SupabaseConfigError('api.enabled must remain false.');

  const auth = requiredObject(root.auth, 'auth');
  const email = requiredObject(auth.email, 'auth.email');
  const rateLimit = requiredObject(auth.rate_limit, 'auth.rate_limit');

  const jwtExpiry = requiredNumber(auth.jwt_expiry, 'auth.jwt_expiry');
  if (jwtExpiry <= 0 || jwtExpiry > 900)
    throw new SupabaseConfigError('auth.jwt_expiry must be between 1 and 900 seconds.');

  for (const key of [
    'secure_password_change',
    'double_confirm_changes',
    'enable_confirmations',
  ] as const) {
    if (email[key] !== true) throw new SupabaseConfigError(`auth.email.${key} must be true.`);
  }

  validateHttpsRedirects(auth.additional_redirect_urls);

  const otpLength = requiredNumber(email.otp_length, 'auth.email.otp_length');
  const otpExpiry = requiredNumber(email.otp_expiry, 'auth.email.otp_expiry');
  if (otpLength < 8 || otpLength > 10)
    throw new SupabaseConfigError('auth.email.otp_length must be between 8 and 10 digits.');
  if (otpExpiry <= 0 || otpExpiry > 600)
    throw new SupabaseConfigError('auth.email.otp_expiry must be between 1 and 600 seconds.');

  for (const [key, cap] of [
    ['sign_in_sign_ups', 30],
    ['token_verifications', 30],
    ['email_sent', 300],
  ] as const) {
    const value = requiredNumber(rateLimit[key], `auth.rate_limit.${key}`);
    if (value <= 0 || value > cap)
      throw new SupabaseConfigError(`auth.rate_limit.${key} must be between 1 and ${cap}.`);
  }

  const hooks = requiredObject(auth.hook, 'auth.hook');
  const beforeUserCreated = requiredObject(
    hooks.before_user_created,
    'auth.hook.before_user_created',
  );
  if (beforeUserCreated.enabled !== true)
    throw new SupabaseConfigError('auth.hook.before_user_created.enabled must be true.');
  if (beforeUserCreated.uri !== 'pg-functions://postgres/identity/before_user_created') {
    throw new SupabaseConfigError(
      'auth.hook.before_user_created.uri must point to the specified identity hook.',
    );
  }

  const approved = new Set(approvedOverrides);
  for (const pathName of ['auth.enable_anonymous_sign_ins', 'auth.enable_manual_linking']) {
    const current = getAtPath(root, pathName.split('.'));
    if (current === true) {
      if (!approved.has(pathName))
        throw new SupabaseConfigError(
          `${pathName}=true requires an approved allow-override marker.`,
        );
      const captcha = isPlainObject(auth.captcha) ? auth.captcha : undefined;
      if (
        captcha?.enabled !== true ||
        typeof captcha.provider !== 'string' ||
        captcha.provider.length === 0
      ) {
        throw new SupabaseConfigError(
          `${pathName}=true requires auth.captcha.enabled and a non-empty provider.`,
        );
      }
      assertEnvReference(captcha.secret, 'auth.captcha.secret');
    }
  }

  validateDisabledSurface(auth.external, ['auth', 'external'], approved);
  validateDisabledSurface(auth.mfa, ['auth', 'mfa'], approved);
  validateDisabledSurface(auth.sms, ['auth', 'sms'], approved);
  validateDisabledSurface(auth.saml, ['auth', 'saml'], approved);
  validateDisabledSurface(auth.oauth_server, ['auth', 'oauth_server'], approved);
  validateDisabledSurface(auth.web3, ['auth', 'web3'], approved);

  const smtp = requiredObject(email.smtp, 'auth.email.smtp');
  if (smtp.enabled !== false && smtp.enabled !== true)
    throw new SupabaseConfigError('auth.email.smtp.enabled must be an explicit boolean.');
  if (Object.hasOwn(smtp, 'host')) assertEnvReference(smtp.host, 'auth.email.smtp.host');
  if (Object.hasOwn(smtp, 'pass') && smtp.pass !== '')
    assertEnvReference(smtp.pass, 'auth.email.smtp.pass');
  if (smtp.enabled === true) {
    if (!approved.has('auth.email.smtp.enabled'))
      throw new SupabaseConfigError(
        'auth.email.smtp.enabled=true requires an approved allow-override marker.',
      );
    if (
      typeof smtp.port !== 'number' ||
      !Number.isInteger(smtp.port) ||
      smtp.port < 1 ||
      smtp.port > 65535
    ) {
      throw new SupabaseConfigError(
        'auth.email.smtp.port must be an integer between 1 and 65535 when SMTP is enabled.',
      );
    }
    if (typeof smtp.user !== 'string' || smtp.user.length === 0)
      throw new SupabaseConfigError('auth.email.smtp.user must be set when SMTP is enabled.');
    if (
      typeof smtp.admin_email !== 'string' ||
      !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(smtp.admin_email)
    ) {
      throw new SupabaseConfigError(
        'auth.email.smtp.admin_email must be a valid address when SMTP is enabled.',
      );
    }
    assertEnvReference(smtp.pass, 'auth.email.smtp.pass');
  }
  checkSecretValues(root);
}

function pathListForChangedValues(before: unknown, after: unknown): string[] {
  return changedLeafPaths(before, after)
    .filter((segments) => segments.length > 0 && getAtPath(before, segments) !== undefined)
    .map((segments) => segments.join('.'));
}

export function renderSupabaseConfig(
  baseSource: string,
  fragments: readonly ConfigFragment[],
): RenderedSupabaseConfig {
  const base = parseToml(baseSource, 'supabase/config.base.toml');
  if (
    parseOverrideMarkers({ name: 'supabase/config.base.toml', contents: baseSource }).length > 0
  ) {
    throw new SupabaseConfigError('config.base.toml cannot contain allow-override markers.');
  }
  checkSecretValues(base);

  const ordered = [...fragments].sort((left, right) =>
    left.name < right.name ? -1 : left.name > right.name ? 1 : 0,
  );
  const seenNames = new Set<string>();
  let merged = base;
  const allMarkers = new Set<string>();

  for (const fragment of ordered) {
    if (seenNames.has(fragment.name))
      throw new SupabaseConfigError(`Duplicate Supabase config fragment: ${fragment.name}.`);
    seenNames.add(fragment.name);
    const overlay = parseToml(fragment.contents, fragment.name);
    checkSecretValues(overlay);
    const markers = parseOverrideMarkers(fragment);
    const next = mergeObjects(merged, overlay);
    validateOverrideMarkers(merged, next, fragment, markers);
    for (const marker of markers) allMarkers.add(marker.path);
    merged = next;
  }

  const approvedOverrides = [...allMarkers].sort();
  validateSupabaseConfig(merged, approvedOverrides);

  const coreOverrides = pathListForChangedValues(base, merged).sort();
  let serialized: string;
  try {
    serialized = TOML.stringify(merged);
  } catch (error) {
    const detail = error instanceof Error ? error.message : 'unknown serializer error';
    throw new SupabaseConfigError(`Could not serialize merged Supabase config: ${detail}`);
  }

  const roundTrip = parseToml(serialized, 'generated supabase/config.toml');
  if (!tomlValuesEqual(merged, roundTrip))
    throw new SupabaseConfigError(
      'Generated TOML does not preserve the merged configuration values.',
    );
  validateSupabaseConfig(roundTrip, approvedOverrides);

  const header = [...generatedHeader];
  header.push(`# Core keys overridden: ${coreOverrides.length === 0 ? 'none' : ''}`);
  for (const pathName of coreOverrides) header.push(`#   - ${pathName}`);
  header.push(`# Approved allow-override keys: ${approvedOverrides.length === 0 ? 'none' : ''}`);
  for (const pathName of approvedOverrides) header.push(`#   - ${pathName}`);

  return {
    text: `${header.join('\n')}\n${serialized.replace(/\n*$/, '\n')}`,
    coreOverrides,
    approvedOverrides,
  };
}

async function assertTomlIsOnlySupabaseConfig(supabaseDirectory: string): Promise<void> {
  for (const alternative of ['config.json', 'config.jsonc']) {
    const candidate = path.join(supabaseDirectory, alternative);
    try {
      await stat(candidate);
      throw new SupabaseConfigError(
        `supabase/${alternative} is forbidden because Supabase CLI gives JSON configuration precedence over config.toml.`,
      );
    } catch (error) {
      if (error instanceof SupabaseConfigError) throw error;
      if (!(error instanceof Error) || !('code' in error) || error.code !== 'ENOENT') throw error;
    }
  }
}

async function loadFragments(supabaseDirectory: string): Promise<ConfigFragment[]> {
  const fragmentsDirectory = path.join(supabaseDirectory, 'config.d');
  const entries = await readdir(fragmentsDirectory, { withFileTypes: true });
  const fileNames = entries
    .filter((entry) => entry.name.endsWith('.toml'))
    .map((entry) => entry.name);
  const fragments: ConfigFragment[] = [];

  for (const name of fileNames) {
    const entry = entries.find((candidate) => candidate.name === name);
    if (!entry?.isFile())
      throw new SupabaseConfigError(
        `supabase/config.d/${name} must be a regular file, not a symlink or directory.`,
      );
    fragments.push({
      name,
      contents: await readFile(path.join(fragmentsDirectory, name), 'utf8'),
    });
  }
  return fragments;
}

export interface SupabaseConfigCommandResult {
  readonly configPath: string;
  readonly mode: 'generated' | 'checked';
  readonly coreOverrides: readonly string[];
  readonly approvedOverrides: readonly string[];
}

export async function generateOrCheckSupabaseConfig(
  projectRoot = process.cwd(),
  mode: 'generate' | 'check' = 'generate',
): Promise<SupabaseConfigCommandResult> {
  const supabaseDirectory = path.join(projectRoot, 'supabase');
  await assertTomlIsOnlySupabaseConfig(supabaseDirectory);
  const baseSource = await readFile(path.join(supabaseDirectory, 'config.base.toml'), 'utf8');
  const fragments = await loadFragments(supabaseDirectory);
  const rendered = renderSupabaseConfig(baseSource, fragments);
  const configPath = path.join(supabaseDirectory, 'config.toml');

  if (mode === 'check') {
    const committed = await readFile(configPath, 'utf8');
    if (committed !== rendered.text) {
      throw new SupabaseConfigError(
        'supabase/config.toml is out of date; run pnpm supabase:config and commit the generated result.',
      );
    }
    return {
      configPath,
      mode: 'checked',
      coreOverrides: rendered.coreOverrides,
      approvedOverrides: rendered.approvedOverrides,
    };
  }

  await writeFile(configPath, rendered.text, 'utf8');
  return {
    configPath,
    mode: 'generated',
    coreOverrides: rendered.coreOverrides,
    approvedOverrides: rendered.approvedOverrides,
  };
}

export async function runSupabaseConfigCli(
  args: readonly string[],
  projectRoot = process.cwd(),
): Promise<void> {
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    throw new SupabaseConfigError('Usage: supabase-config [--check].');
  }
  const mode = args[0] === '--check' ? 'check' : 'generate';
  const result = await generateOrCheckSupabaseConfig(projectRoot, mode);
  process.stdout.write(
    `${result.mode === 'checked' ? 'Supabase config is current' : 'Generated supabase/config.toml'}.\n`,
  );
}
