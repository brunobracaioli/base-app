type TomlTable = Record<string, unknown>;

function table(value: unknown): TomlTable {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
    ? { ...(value as TomlTable) }
    : {};
}

/**
 * Derives the local-only Supabase config from the generated `supabase/config.toml`. The committed
 * config is never edited: the result goes to the git-ignored work directory used by `pnpm dev`.
 */
export function buildLocalSupabaseConfig(source: string): string {
  const config = parse(source) as TomlTable;
  const db = table(config.db);
  db.port = LOCAL_PORTS.db;
  db.shadow_port = LOCAL_PORTS.shadowDb;
  db.pooler = { ...table(db.pooler), enabled: false };

  const local: TomlTable = {
    ...config,
    project_id: LOCAL_PROJECT_ID,
    api: { ...table(config.api), port: LOCAL_PORTS.api },
    db,
    studio: { ...table(config.studio), enabled: false, port: LOCAL_PORTS.studio },
    local_smtp: {
      ...table(config.local_smtp),
      enabled: true,
      port: LOCAL_PORTS.mail,
      smtp_port: LOCAL_PORTS.smtp,
      pop3_port: LOCAL_PORTS.pop3,
    },
    analytics: { ...table(config.analytics), enabled: false },
    edge_runtime: { ...table(config.edge_runtime), enabled: false },
    auth: { ...table(config.auth), signing_keys_path: './signing_keys.json' },
  };
  return `# Generated by \`pnpm dev\` from supabase/config.toml. Do not edit; local use only.\n${stringify(local)}\n`;
}

/** ES256 signing key in the JWK format the Supabase CLI expects (`signing_keys.json` array). */
export function generateLocalSigningKeys(): string {
  const { privateKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' });
  const jwk = privateKey.export({ format: 'jwk' });
  return `${JSON.stringify(
    [
      {
        ...jwk,
        kid: randomUUID(),
        alg: 'ES256',
        use: 'sig',
        key_ops: ['sign', 'verify'],
        ext: true,
      },
    ],
    null,
    2,
  )}\n`;
}

export type LocalSecrets = {
  readonly apiRuntimePassword: string;
  readonly redisToken: string;
  readonly auditSubjectKey: string;
};

const SECRET_PATTERN = /^[A-Za-z0-9_-]{40,128}$/;

export function generateLocalSecrets(): LocalSecrets {
  return {
    apiRuntimePassword: randomBytes(32).toString('base64url'),
    redisToken: randomBytes(32).toString('base64url'),
    auditSubjectKey: randomBytes(48).toString('base64url'),
  };
}

export function parseLocalSecrets(source: string): LocalSecrets | null {
  try {
    const value = JSON.parse(source) as Partial<Record<keyof LocalSecrets, unknown>>;
    const secrets = {
      apiRuntimePassword: value.apiRuntimePassword,
      redisToken: value.redisToken,
      auditSubjectKey: value.auditSubjectKey,
    };
    return Object.values(secrets).every(
      (entry) => typeof entry === 'string' && SECRET_PATTERN.test(entry),
    )
      ? (secrets as LocalSecrets)
      : null;
  } catch {
    return null;
  }
}

const IGNORED_INTERFACE =
  /docker|^br-|veth|vethernet|virtualbox|vboxnet|vmnet|utun|tailscale|zerotier|wsl|loopback/i;

function privateRank(address: string): number | null {
  const octets = address.split('.').map(Number);
  if (octets.length !== 4 || octets.some((octet) => !Number.isInteger(octet))) return null;
  const [first, second] = octets as [number, number, number, number];
  if (first === 192 && second === 168) return 1;
  if (first === 10) return 2;
  if (first === 172 && second >= 16 && second <= 31) return 3;
  return null;
}

/**
 * Picks the private IPv4 the phone can reach on the same Wi-Fi. Prefers home-router ranges and
 * skips virtual adapters (Docker, WSL, VPNs). Returns null when there is no private network.
 */
export function pickLanAddress(
  interfaces: Readonly<Record<string, readonly NetworkInterfaceInfo[] | undefined>>,
): string | null {
  const candidates: { address: string; rank: number }[] = [];
  for (const [name, entries] of Object.entries(interfaces)) {
    if (IGNORED_INTERFACE.test(name)) continue;
    for (const entry of entries ?? []) {
      if (entry.family !== 'IPv4' || entry.internal) continue;
      const rank = privateRank(entry.address);
      if (rank !== null) candidates.push({ address: entry.address, rank });
    }
  }
  candidates.sort((left, right) => left.rank - right.rank);
  return candidates[0]?.address ?? null;
}

export function isPrivateLanAddress(address: string): boolean {
  return privateRank(address) !== null;
}

/**
 * Supabase Auth endpoints a mobile client calls. Everything else under /auth/v1 (admin, invite)
 * needs the service key, which is a well-known value in local Supabase, so it must never reach
 * the network.
 */
const PUBLIC_AUTH_ENDPOINTS = new Set([
  '.well-known',
  'factors',
  'health',
  'logout',
  'magiclink',
  'otp',
  'reauthenticate',
  'recover',
  'resend',
  'settings',
  'signup',
  'token',
  'user',
  'verify',
]);

export type GatewayTarget = 'auth' | 'api';

/**
 * Routing rule of the local network gateway (the only listener `pnpm dev` opens on the Wi-Fi
 * besides Metro): public Auth endpoints go to the local Supabase gateway, `/api/*` goes to the
 * Next.js API (which authenticates every protected route). Anything else, or any ambiguous path,
 * is refused.
 */
export function routeGatewayRequest(rawUrl: string): GatewayTarget | null {
  if (!rawUrl.startsWith('/')) return null;
  const pathEnd = rawUrl.search(/[?#]/);
  const path = pathEnd === -1 ? rawUrl : rawUrl.slice(0, pathEnd);
  if (/[%\\]/.test(path) || path.includes('//') || /\/\.\.?(?:\/|$)/.test(path)) return null;
  if (path.startsWith('/auth/v1/')) {
    const endpoint = path.slice('/auth/v1/'.length).split('/')[0] ?? '';
    return PUBLIC_AUTH_ENDPOINTS.has(endpoint) ? 'auth' : null;
  }
  if (path.startsWith('/api/')) return 'api';
  return null;
}

export const MANAGED_BLOCK_START = '# >>> pnpm dev: generated block, do not edit >>>';
export const MANAGED_BLOCK_END = '# <<< pnpm dev <<<';

/**
 * Writes the managed variables as the last block of a dotenv file, so they win over earlier
 * entries, and keeps every line the student wrote outside the block.
 */
export function upsertManagedEnvBlock(
  existing: string,
  values: Readonly<Record<string, string>>,
): string {
  for (const [key, value] of Object.entries(values)) {
    if (!/^[A-Z][A-Z0-9_]*$/.test(key) || /[\r\n]/.test(value)) {
      throw new Error(`Invalid managed environment entry: ${key}`);
    }
  }
  const lines = existing.split(/\r?\n/);
  const kept: string[] = [];
  let inside = false;
  for (const line of lines) {
    if (line === MANAGED_BLOCK_START) {
      inside = true;
      continue;
    }
    if (line === MANAGED_BLOCK_END) {
      inside = false;
      continue;
    }
    if (!inside) kept.push(line);
  }
  while (kept.length > 0 && kept[kept.length - 1]?.trim() === '') kept.pop();
  const block = [
    MANAGED_BLOCK_START,
    ...Object.entries(values).map(([key, value]) => `${key}=${value}`),
    MANAGED_BLOCK_END,
  ];
  return `${[...kept, ...(kept.length > 0 ? [''] : []), ...block].join('\n')}\n`;
}

export type SupabaseLocalStatus = {
  readonly apiUrl: string;
  readonly publishableKey: string;
  readonly studioUrl: string | null;
  readonly mailUrl: string | null;
};

function stringField(value: Record<string, unknown>, ...names: string[]): string | null {
  for (const name of names) {
    const entry = value[name];
    if (typeof entry === 'string' && entry.length > 0) return entry;
  }
  return null;
}

/** Reads `supabase status --output json`; only public values are kept. */
export function parseSupabaseStatus(source: string): SupabaseLocalStatus {
  const start = source.indexOf('{');
  const end = source.lastIndexOf('}');
  if (start === -1 || end <= start) throw new Error('Supabase status is not JSON.');
  const value = JSON.parse(source.slice(start, end + 1)) as Record<string, unknown>;
  const apiUrl = stringField(value, 'API_URL');
  const publishableKey = stringField(value, 'PUBLISHABLE_KEY', 'ANON_KEY');
  if (!apiUrl || !publishableKey) throw new Error('Supabase status is missing API_URL or keys.');
  return {
    apiUrl,
    publishableKey,
    studioUrl: stringField(value, 'STUDIO_URL'),
    mailUrl: stringField(value, 'MAILPIT_URL', 'INBUCKET_URL'),
  };
}

const UPSTASH_ONLY_SCRIPT_FLAGS = new Set(['allow-key-locking']);
const SCRIPT_COMMANDS = new Set(['EVAL', 'EVAL_RO']);

function stripScriptFlags(script: string): string {
  const shebang = /^#!lua(?:[ \t]+flags=([^\r\n]*))?/.exec(script);
  if (!shebang?.[1]) return script;
  const kept = shebang[1]
    .split(',')
    .map((flag) => flag.trim())
    .filter((flag) => flag.length > 0 && !UPSTASH_ONLY_SCRIPT_FLAGS.has(flag));
  const header = kept.length > 0 ? `#!lua flags=${kept.join(',')}` : '#!lua';
  return `${header}${script.slice(shebang[0].length)}`;
}

function rewriteCommand(command: unknown): unknown {
  if (!Array.isArray(command) || typeof command[0] !== 'string') return command;
  const name = command[0].toUpperCase();
  const scriptIndex = SCRIPT_COMMANDS.has(name)
    ? 1
    : name === 'SCRIPT' && String(command[1]).toUpperCase() === 'LOAD'
      ? 2
      : -1;
  const script: unknown = command[scriptIndex];
  if (scriptIndex === -1 || typeof script !== 'string') return command;
  return command.map((entry, index) => (index === scriptIndex ? stripScriptFlags(script) : entry));
}

/**
 * `@upstash/ratelimit` marks its Lua scripts with `allow-key-locking`, a flag only Upstash
 * understands; Redis and Valkey reject the script. The local Redis proxy removes that flag from
 * EVAL/SCRIPT LOAD bodies (single command or pipeline) so the API keeps the production code path.
 * Anything that is not a JSON command array passes through unchanged.
 */
export function stripUpstashOnlyScriptFlags(body: string): string {
  let parsed: unknown;
  try {
    parsed = JSON.parse(body);
  } catch {
    return body;
  }
  if (!Array.isArray(parsed)) return body;
  const rewritten = parsed.every((entry) => Array.isArray(entry))
    ? parsed.map(rewriteCommand)
    : rewriteCommand(parsed);
  return JSON.stringify(rewritten);
}

/** Parses `docker ps --format '{{.Ports}}'` rows and tells whether every binding is loopback. */
export function publishedBindingsAreLoopback(rows: readonly string[]): boolean {
  const bindings = rows
    .flatMap((row) => row.split(','))
    .map((binding) => binding.trim())
    .filter((binding) => binding.includes('->'));
  return bindings.every((binding) => binding.startsWith('127.0.0.1:'));
}
